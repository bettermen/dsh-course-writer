let lang: 'zh' | 'en' = 'zh'
try {
  const nav = (typeof navigator !== 'undefined' ? navigator.language : '') || ''
  lang = nav.toLowerCase().startsWith('zh') ? 'zh' : 'en'
} catch {
  lang = 'zh'
}

/** 取当前语言的文案。 */
export function t(key: keyof typeof zh): string {
  return (lang === 'en' ? en[key] : zh[key]) ?? zh[key]
}

/** 当前语言（供需要判断逻辑的地方使用）。 */
export function currentLang(): 'zh' | 'en' {
  return lang
}
