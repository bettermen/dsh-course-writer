let lang: 'zh' | 'en' = 'zh'
try {
  const nav = (typeof navigator !== 'undefined' ? navigator.language : '') || ''
  lang = nav.toLowerCase().startsWith('zh') ? 'zh' : 'en'
} catch {
  lang = 'zh'
}

/** 取当前语言的文案。 */
export function t(key: keyof typeof zh): string {
  return (lang === 'en' ? en[key] : zh[key]) ?? zh[key]
}

/** 当前语言（供需要判断逻辑的地方使用）。 */
export function currentLang(): 'zh' | 'en' {
  return lang
}

/**
 * 带插值的取文案：文案里的 `%s` / `%d` 按出现顺序替换为 args。
 * 例：`tf('confirmDeleteBody', '青云问道')` → '确定删除项目「青云问道」吗？…'
 * 参数不足时剩余占位符保持原样（不抛错，避免 UI 崩掉）。
 */
export function tf(key: keyof typeof zh, ...args: Array<string | number>): string {
  let out = t(key)
  for (const arg of args) out = out.replace(/%[sd]/, String(arg))
  return out
}
